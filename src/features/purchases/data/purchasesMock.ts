function dateFromToday(days: number) {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() + days);
  return date.toISOString().slice(0, 10);
}

function timestampFromToday(days: number) {
  return `${dateFromToday(days)}T14:30:00.000Z`;
}

